// Generates src/py_aep/_modules.ts, the registry hub for pyrt `deferred()`.
//
// Every `deferred<typeof import("./x.ts")>("<key>")` in src names its target
// by key = the target's path relative to src without `.ts`. The hub imports
// each target and registers it under that key; py_aep/index.ts imports the
// hub last, so a bundler sees every deferred target as a static import.
//
// usage: bun tools/gen_deferred_modules.ts          rewrite the hub
//        bun tools/gen_deferred_modules.ts --check  exit 1 if it is stale or a key is wrong

import * as fs from "node:fs";
import * as path from "node:path";

const ROOT = path.resolve(import.meta.dir, "..");
const SRC = path.join(ROOT, "src");
const HUB = path.join(SRC, "py_aep", "_modules.ts");
const CALL = /deferred<typeof import\("([^"]+)"\)>\(\s*"([^"]+)"\s*\)/g;

function walk(dir: string): string[] {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) => {
    const full = path.join(dir, e.name);
    return e.isDirectory() ? walk(full) : e.name.endsWith(".ts") ? [full] : [];
  });
}

const keys = new Set<string>();
const errors: string[] = [];
for (const file of walk(SRC).sort()) {
  const text = fs
    .readFileSync(file, "utf8")
    .split("\n")
    .filter((line) => !line.trimStart().startsWith("//"))
    .join("\n");
  for (const m of text.matchAll(CALL)) {
    const target = path.resolve(path.dirname(file), m[1]);
    const want = path.relative(SRC, target).replace(/\.ts$/, "").split(path.sep).join("/");
    if (m[2] !== want) errors.push(`${path.relative(ROOT, file)}: deferred key "${m[2]}" should be "${want}"`);
    keys.add(want);
  }
}
if (errors.length) {
  console.error(errors.join("\n"));
  process.exit(1);
}

const sorted = [...keys].sort();
const spec = (key: string) => {
  const rel = path.relative(path.dirname(HUB), path.join(SRC, key + ".ts")).split(path.sep).join("/");
  return rel.startsWith(".") ? rel : "./" + rel;
};
const hub = [
  "// Generated by tools/gen_deferred_modules.ts; do not edit.",
  "// Registers every module a pyrt `deferred(\"<key>\")` call loads.",
  "",
  'import { register } from "../pyrt/deferred.ts";',
  ...sorted.map((k, i) => `import * as m${i} from "${spec(k)}";`),
  "",
  ...sorted.map((k, i) => `register("${k}", m${i});`),
  "",
].join("\n");

if (process.argv.includes("--check")) {
  const current = fs.existsSync(HUB) ? fs.readFileSync(HUB, "utf8") : "";
  if (current !== hub) {
    console.error("src/py_aep/_modules.ts is stale: run bun tools/gen_deferred_modules.ts");
    process.exit(1);
  }
  console.log(`_modules.ts up to date (${sorted.length} deferred targets)`);
} else {
  fs.writeFileSync(HUB, hub);
  console.log(`wrote src/py_aep/_modules.ts (${sorted.length} deferred targets)`);
}
